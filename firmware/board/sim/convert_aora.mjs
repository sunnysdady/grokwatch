// Convert the selected upstream aora-bot eye contours to compact, immutable data.
// Usage: node convert_aora.mjs /path/to/aora-bot /path/to/gw_aora_data.h
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

const [root, output] = process.argv.slice(2);
if (!root || !output) throw new Error('upstream checkout and output path required');
const context = vm.createContext({window: {}});
for (const name of ['rings', 'emotions']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'emotion-ball/js', name + '.js'), 'utf8'), context, {timeout: 1000});
}
const {EB_RINGS: rings, EMOTION_SEED: emotions} = context.window;
const ids = ['02', '35', '30', '10', '12']; // idle, listening, thinking, speaking, offline
const states = ids.map(id => emotions.find(e => e.id === id));
const used = [...new Set(states.flatMap(e => e.pool))];
const sha = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim();
const points = used.map(id => rings.EXPRESSIONS[id].map(eye => {
  if (eye.length !== 48) throw new Error('Expected 48-point eye contour');
  return '{' + eye.map(pt => '{' + pt.map(v => Math.round((v - rings.HEAD_C) * 100)).join(',') + '}').join(',') + '}';
}));
const configs = states.map(e => {
  if (e.pool.length > 5) throw new Error('Pool exceeds static capacity');
  return '    {' + [e.pool.length, '{' + e.pool.map(i => used.indexOf(i)).join(',') + '}',
    Math.round((e.poolMs[0] + e.poolMs[1]) / 2), Math.round((e.blinkMs[0] + e.blinkMs[1]) / 2), e.transition].join(',') + '}, // ' + e.id + ' ' + e.name;
});
fs.writeFileSync(output, `// SPDX-FileCopyrightText: 2026 sam70361
// SPDX-License-Identifier: LicenseRef-Emotion-Ball-Community
// Generated by sim/convert_aora.mjs from sam70361/aora-bot ${sha}.
// Personal non-commercial use; retain third_party/aora/LICENSE and NOTICE.md.
// Eye points relative to HEAD_C, in 1/100 upstream units. No heap ownership.
#pragma once
#include <stdint.h>
typedef struct { uint8_t count, pool[5]; uint16_t pool_ms, blink_ms, transition_ms; } gw_aora_cfg_t;
static const int16_t gw_aora_eyes[${used.length}][2][48][2] = {
${points.map(p => '    {' + p.join(',') + '}').join(',\n')}
};
static const gw_aora_cfg_t gw_aora_cfg[5] = {
${configs.join('\n')}
};
`);
console.log(`Converted ${used.length} eye pairs for ${states.length} device states at ${sha}`);
